"""Generates internal/store/seed_generated.go from the research snapshot in
data/raw so the mock database ships with real fixtures.

    python3 -I backend/tools/gen_seed.py
"""
import gzip
import ipaddress
import json
import pathlib
import tarfile

ROOT = pathlib.Path(__file__).resolve().parents[2]
RAW = ROOT / "data" / "raw"
OUT = ROOT / "backend" / "internal" / "store" / "seed_generated.go"

# IPs whose iptoasn ranges we embed (real routers / services used in tests and demos).
SEED_IPS = [
    "8.8.8.8", "1.1.1.1", "9.9.9.9", "49.36.0.1", "180.87.38.1", "80.231.153.1",
    "80.231.200.1", "18.96.32.10", "52.93.0.1", "4.69.140.98", "184.105.64.1",
    "62.115.0.1", "129.250.0.1", "154.54.0.1", "27.56.0.1", "1.38.0.1",
    "65.76.0.1", "13.107.42.14", "142.250.0.1", "151.101.1.1",
]
SEED_CABLES = [
    "imewe", "seamewe-4", "seamewe-5", "2africa", "asia-africa-europe-1-aae-1", "marea",
    "dunant", "grace-hopper", "amitie", "jupiter", "faster", "peace-cable",
    "equiano", "india-europe-xpress-iex", "seacomtata-tgn-eurasia", "tata-tgn-western-europe", "tata-tgn-pacific", "tata-tgn-tata-indicom",
]


def country_name_map():
    ne = json.load(gzip.open(RAW / "naturalearth" / "ne_50m_admin_0_countries.geojson.gz", "rt"))
    m = {}
    for f in ne["features"]:
        p = f["properties"]
        iso = p["ISO_A2"] if p["ISO_A2"] != "-99" else p["ISO_A2_EH"]
        if iso == "-99":
            continue
        for k in ("NAME", "NAME_LONG", "ADMIN", "FORMAL_EN", "NAME_SORT", "BRK_NAME", "GEOUNIT"):
            if p.get(k):
                m[p[k].lower()] = iso
    m.update({"united states": "US", "russia": "RU", "korea, rep.": "KR", "congo, dem. rep.": "CD",
              "congo, rep.": "CG", "côte d'ivoire": "CI", "egypt": "EG", "iran": "IR",
              "virgin islands (u.s.)": "VI", "hong kong": "HK", "macau": "MO", "taiwan": "TW",
              "syria": "SY", "yemen": "YE", "gambia": "GM", "bahamas": "BS", "micronesia": "FM",
              "turkey": "TR", "türkiye": "TR", "vietnam": "VN", "brunei": "BN", "laos": "LA"})
    return m


def asn_ranges():
    want = [ipaddress.ip_address(x) for x in SEED_IPS]
    found = {}
    for line in gzip.open(RAW / "iptoasn" / "ip2asn-combined.tsv.gz", "rt"):
        s, e, asn, cc, name = line.rstrip("\n").split("\t")
        if ":" in s or asn == "0":
            continue
        a, b = ipaddress.ip_address(s), ipaddress.ip_address(e)
        for ip in want:
            if a <= ip <= b:
                found[(s, e)] = (int(asn), cc, name)
    return sorted(found.items(), key=lambda kv: ipaddress.ip_address(kv[0][0]))


def cables(names):
    lp = json.load(gzip.open(RAW / "telegeography" / "landing-point_landing-point-geo.json.gz", "rt"))
    coords = {f["properties"]["id"]: f["geometry"]["coordinates"] for f in lp["features"]}
    out = []
    with tarfile.open(RAW / "telegeography" / "cables-detail.tar.gz") as t:
        for cid in SEED_CABLES:
            c = json.load(t.extractfile(f"cables/{cid}.json"))
            lands = []
            for l in c["landing_points"]:
                iso = names.get(l["country"].lower())
                if not iso or l["id"] not in coords:
                    continue
                lon, lat = coords[l["id"]]
                lands.append((l["id"], l["name"], iso, round(lat, 4), round(lon, 4)))
            length = float((c.get("length") or "0").split(" ")[0].replace(",", "") or 0)
            owners = [o.strip() for o in (c.get("owners") or "").split(",") if o.strip()]
            out.append((c["id"], c["name"], length, c.get("rfs_year") or 0, bool(c.get("is_planned")), owners, lands))
    return out


def q(s):
    return json.dumps(s, ensure_ascii=False)


def main():
    names = country_name_map()
    lines = [
        "// Code generated by tools/gen_seed.py from data/raw (2026-11-02 snapshot). DO NOT EDIT.",
        "",
        "package store",
        "",
        "// seedASNRanges are real iptoasn.com ranges covering the demo/test IPs.",
        "var seedASNRanges = []asnRangeSeed{",
    ]
    for (s, e), (asn, cc, name) in asn_ranges():
        lines.append(f"\t{{{q(s)}, {q(e)}, {asn}, {q(cc)}, {q(name)}}},")
    lines += ["}", "", "// seedCables are real TeleGeography cables (CC BY-NC-SA 3.0).", "var seedCables = []Cable{"]
    for cid, name, length, rfs, planned, owners, lands in cables(names):
        lines.append(f"\t{{ID: {q(cid)}, Name: {q(name)}, LengthKM: {length}, RFSYear: {rfs}, Planned: {str(planned).lower()},")
        lines.append(f"\t\tOwners: []string{{{', '.join(q(o) for o in owners)}}},")
        lines.append("\t\tLandings: []LandingPoint{")
        for lid, lname, iso, lat, lon in lands:
            lines.append(f"\t\t\t{{ID: {q(lid)}, Name: {q(lname)}, CountryISO2: {q(iso)}, Lat: {lat}, Lon: {lon}}},")
        lines.append("\t\t}},")
    lines.append("}")
    OUT.write_text("\n".join(lines) + "\n")
    print("wrote", OUT)


if __name__ == "__main__":
    main()
